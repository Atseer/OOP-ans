namespace ClassAndObject.OperasiMatematika;

public class Kalkulator
{
    public void Tambah(double x, double y)
    {
        return x + y;
    }
    public void Kurang(double x, double y)
    {
        return x - y;
    }
    public void Kali(double x, double y)
    {
        return x*y;
    }
    public void Bagi(double x, double y)
    {
        return x/y;
    }
}